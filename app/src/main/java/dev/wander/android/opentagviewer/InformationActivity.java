public class InformationActivity extends AppCompatActivity {
    private static final String TAG = InformationActivity.class.getSimpleName();

    /** Both generated by scripts/fetch_contributors.py; see the workflow that runs it. */
    private static final String CONTRIBUTORS_ASSET = "contributors.json";
    private static final String AVATAR_ASSET_DIR = "contributors";

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);

        ActivityInformationBinding binding = DataBindingUtil.setContentView(this, R.layout.activity_information);
        WindowPaddingUtil.insertUITopPadding(binding.getRoot());
        binding.setHandleClickBack(this::finish);

        if (this.getSupportActionBar() != null) {
            this.getSupportActionBar().hide();
        }

        try {
            TextView version = findViewById(R.id.appVersion);
            var info = getPackageManager().getPackageInfo(getPackageName(), 0);
            var filledVersionString = String.format(
                    getResources().getString(R.string.version_x),
                    info.versionName
            );
            version.setText(filledVersionString);

        } catch (PackageManager.NameNotFoundException e) {
            throw new RuntimeException(e);
        }

        this.showWhereTheTagsCameFrom();
        this.showContributors();

        ViewCompat.setOnApplyWindowInsetsListener(findViewById(R.id.main), (v, insets) -> {
            Insets systemBars = insets.getInsets(WindowInsetsCompat.Type.systemBars());
            v.setPadding(systemBars.left, systemBars.top, systemBars.right, systemBars.bottom);
            return insets;
        });
    }

    /**
     * Says which exporter produced the bundle these tags were imported from.
     *
     * <p><b>Because the issue template asks, and the honest alternative was worse.</b> The
     * {@code via:} line is inside {@code OPENTAGVIEWER.yml} in the export zip - a file holding
     * the private keys to somebody's tags, which the template tells them in bold not to open.
     * Asking a question whose answer is in a file you have told people not to open is asking
     * them to ignore you.
     *
     * <p><b>All of them, not the most recent one.</b> Importing twice is ordinary, and naming
     * only the newest bundle would state one producer as though it accounted for every tag on
     * the phone. Where a report says 1.3.0 and half the tags came out of 1.1.0, whoever reads it
     * goes looking in the wrong place - which is the same failure as the import error that named
     * the wrong phase, one level up.
     *
     * <p>Off the main thread: Room refuses a query on it, so doing this inline would not be slow,
     * it would throw.
     */
    private void showWhereTheTagsCameFrom() {
        final TextView importedFrom = this.findViewById(R.id.appImportedFrom);
        if (importedFrom == null) {
            return;
        }

        var async = Observable.fromCallable(() -> OpenTagViewerDatabase
                        .getInstance(this.getApplicationContext())
                        .importDao().getDistinctProducers())
                .subscribeOn(Schedulers.io())
                .observeOn(AndroidSchedulers.mainThread())
                .subscribe(
                        producers -> importedFrom.setText(producers.isEmpty()
                                ? this.getString(R.string.imported_from_nothing)
                                : this.getString(R.string.imported_from_x,
                                        String.join(", ", producers))),
                        error -> {
                            // A line that cannot be read is not worth a broken screen; the
                            // version above it is still the more important half.
                            Log.w(TAG, "Could not read where the tags were imported from", error);
                            importedFrom.setVisibility(View.GONE);
                        });
    }

    /**
     * Fills the avatar grid from the list bundled at build time.
     * <br>
     * Read from assets rather than fetched, which is what
     * {@code scripts/fetch_contributors.py} exists for. Calling the GitHub API here would be
     * rate limited in practice - it allows 60 requests an hour per IP, and carrier-grade NAT
     * puts a great many users behind each one - and it would hand every user's IP to GitHub
     * on opening a screen that shows no remote content otherwise.
     */
    private void showContributors() {
        FlowLayout grid = findViewById(R.id.contributors_flow);
        if (grid == null) {
            return;
        }

        final List<Contributor> contributors = readContributors();
        if (contributors.isEmpty()) {
            // Nothing to show, so give the space back to the rest of the page.
            findViewById(R.id.contributors_scroll).setVisibility(View.GONE);
            return;
        }

        final LayoutInflater inflater = getLayoutInflater();

        for (Contributor contributor : contributors) {
            ShapeableImageView avatar = (ShapeableImageView)
                    inflater.inflate(R.layout.contributor_avatar, grid, false);

            Bitmap bitmap = readAvatar(contributor.avatar);
            if (bitmap == null) {
                // The manifest and the images are generated together, so this only happens if
                // one of them was edited by hand. Skip rather than show an empty circle.
                Log.w(TAG, "No bundled avatar for " + contributor.login + "; skipping");
                continue;
            }
            avatar.setImageBitmap(bitmap);
            avatar.setContentDescription(contributor.login);

            // Long press rather than a tooltip attribute: works below API 26 too.
            TooltipCompat.setTooltipText(avatar, contributor.login);

            avatar.setOnClickListener(v -> openUrl(contributor.profileUrl));

            grid.addView(avatar);
        }
    }

    private List<Contributor> readContributors() {
        try (InputStream in = getAssets().open(CONTRIBUTORS_ASSET)) {
            ContributorsFile parsed = new ObjectMapper()
                    .configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, false)
                    .readValue(in, ContributorsFile.class);

            return parsed.contributors == null ? List.of() : parsed.contributors;
        } catch (IOException e) {
            Log.w(TAG, "Could not read " + CONTRIBUTORS_ASSET, e);
            return List.of();
        }
    }

    private Bitmap readAvatar(final String filename) {
        if (filename == null || filename.isBlank()) {
            return null;
        }

        try (InputStream in = getAssets().open(AVATAR_ASSET_DIR + "/" + filename)) {
            return BitmapFactory.decodeStream(in);
        } catch (IOException e) {
            Log.w(TAG, "Could not read avatar " + filename, e);
            return null;
        }
    }

    private void openUrl(final String url) {
        WebLink.open(this, url);
    }

    /** Shape of assets/contributors.json. */
    public static class ContributorsFile {
        public List<Contributor> contributors;
    }

    public static class Contributor {
        public String login;
        public String profileUrl;
        public String avatar;
        public int commits;
    }



    public void onClickWiki(View view) {
        Log.d(TAG, "Clicked App Wiki button");

        var properties = PropertiesUtil.getProperties(this.getAssets(), "app.properties");
        assert properties != null;
        WebLink.open(this, properties.getProperty("projectWiki"));
    }

    public void onClickGithub(View view) {
        Log.d(TAG, "Clicked Github button");

        var properties = PropertiesUtil.getProperties(this.getAssets(), "app.properties");
        assert properties != null;
        WebLink.open(this, properties.getProperty("projectGithub"));
    }
}